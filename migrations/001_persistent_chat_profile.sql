-- This RPC moves settings/music ownership and the username in one transaction.
create or replace function public.flash_update_profile(p_user_id bigint, p_new_username text, p_display_name text)
returns table(id bigint, username text, display_name text, avatar_url text, last_seen_at timestamptz)
language plpgsql security definer set search_path = public, pg_temp
as $$
declare old_username text;
begin
  if p_new_username !~ '^[a-z0-9_.-]{3,24}$' or length(p_display_name) < 1 or length(p_display_name) > 48 then
    raise exception 'Invalid profile data.' using errcode = '22023';
  end if;
  select u.username into old_username from public.users u where u.id = p_user_id for update;
  if old_username is null then raise exception 'User not found.' using errcode = 'P0002'; end if;
  if exists (select 1 from public.users u where u.username = p_new_username and u.id <> p_user_id) then
    raise exception 'Username already exists.' using errcode = '23505';
  end if;
  if old_username <> p_new_username then
    update public.settings s
       set key = p_new_username || substr(s.key, length(old_username) + 1)
     where left(s.key, length(old_username) + 1) = old_username || ':';
    update public.music m set uploader = p_new_username where m.uploader_id = p_user_id;
  end if;
  update public.users u set username = p_new_username, display_name = p_display_name where u.id = p_user_id;
  return query select u.id, u.username, u.display_name, u.avatar_url, u.last_seen_at from public.users u where u.id = p_user_id;
end $$;
revoke all on function public.flash_update_profile(bigint, text, text) from public, anon, authenticated;
grant execute on function public.flash_update_profile(bigint, text, text) to service_role;

-- Atomically consume an owner-bound, expiring ticket so multiple app instances work.
create or replace function public.flash_consume_download_ticket(p_token_hash text, p_user_id bigint)
returns table(target text, filename text)
language plpgsql security definer set search_path = public, pg_temp
as $$
declare ticket_target text; ticket_filename text;
begin
  delete from public.download_tickets t
   where t.token_hash = p_token_hash and t.user_id = p_user_id and t.expires_at > now()
   returning t.target, t.filename into ticket_target, ticket_filename;
  if not found then return; end if;
  return query select ticket_target, ticket_filename;
end $$;
revoke all on function public.flash_consume_download_ticket(text, bigint) from public, anon, authenticated;
grant execute on function public.flash_consume_download_ticket(text, bigint) to service_role;


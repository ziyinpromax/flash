create extension if not exists pgcrypto;

-- Stop before changing data if a legacy username cannot be safely supported.
do $$ begin
  if exists (select 1 from public.users where username !~ '^[A-Za-z0-9_.-]{3,24}$') then
    raise exception 'Cannot migrate usernames outside the new 3-24 character ASCII username rules; rename those accounts first.';
  end if;
end $$;

-- The app now accepts lowercase usernames only. Abort safely if legacy accounts
-- would collide after case normalization; resolve those accounts before rerunning.
do $$ begin
  if exists (
    select lower(username) from public.users group by lower(username) having count(*) > 1
  ) then
    raise exception 'Cannot lowercase usernames: duplicate accounts differ only by letter case.';
  end if;
end $$;

update public.settings s
set key = lower(u.username) || substr(s.key, length(u.username) + 1)
from public.users u
where left(s.key, length(u.username) + 1) = u.username || ':'
  and u.username <> lower(u.username);
update public.music m
set uploader = lower(u.username)
from public.users u
where m.uploader = u.username and u.username <> lower(u.username);
update public.users set username = lower(username) where username <> lower(username);

